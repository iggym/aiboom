def _provenance(bom: dict[str, Any], app_props: dict[str, str], digest: str) -> list[str]:
    metadata = bom.get("metadata") or {}
    tools = metadata.get("tools") or {}
    tool_components = tools.get("components") if isinstance(tools, dict) else None
    tool_text = "—"
    if tool_components:
        tool_text = ", ".join(
            f"{c.get('name')} {c.get('version', '')}".strip() for c in tool_components
        )
    return [
        "---",
        "",
        "## Provenance",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Git commit | {_code(app_props.get('aibom:git_commit'))} |",
        f"| Git branch | {_code(app_props.get('aibom:git_branch'))} |",
        f"| Git tag | {_code(app_props.get('aibom:git_tag'))} |",
        f"| Working tree | {_esc(app_props.get('aibom:git_dirty'))} |",
        f"| Scanner | {_code(app_props.get('aibom:scanner'))} |",
        f"| Lock | {_code(app_props.get('aibom:lock'))} (fresh: {_esc(app_props.get('aibom:lock_fresh'))}) |",
        f"| Manifest | {_code(app_props.get('aibom:manifest'))} |",
        f"| Generator | {_esc(tool_text)} |",
        f"| Rules version | {_code(app_props.get('aibom:rules_version'))} |",
        f"| CycloneDX | {_esc(bom.get('specVersion'))} |",
        f"| BOM version | {_esc(bom.get('version'))} |",
        f"| Serial number | {_code(bom.get('serialNumber'))} |",
        f"| **Content digest (sha256)** | `{digest}` |",
        "",
        f"Verify this document with `aibom verify {_code('aibom.cdx.json')}`. The digest covers the BOM with "
        "`serialNumber`, `metadata.timestamp` and `version` removed, so it is stable across regenerations.",
        "",
    ]


